// Home's Phosphor icons with only the weights the app draws (bold, fill), so the first paint does not carry all
// six weights of each (thin…duotone). Same drawing data and props as @phosphor-icons/react (IconBase). Run after
// adding an icon to Home or bumping the package: `node scripts/icons.mjs`.
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { writeFileSync } from 'node:fs';

const NAMES = [
  'ArrowCounterClockwise',
  'ArrowFatUp',
  'Bank',
  'CalendarDots',
  'Camera',
  'CaretDown',
  'Cardholder',
  'Cards',
  'ChartBar',
  'ClockCountdown',
  'CreditCard',
  'CurrencyBtc',
  'DeviceMobile',
  'Handshake',
  'House',
  'KeyReturn',
  'List',
  'Money',
  'PencilSimple',
  'Question',
  'Wallet',
];
const WEIGHTS = ['bold', 'fill'];
const jsx = html =>
  html
    .replace(/ ([a-z]+)-([a-z])/g, (_, a, b) => ` ${a}${b.toUpperCase()}`)
    .replace(/><\/(path|circle|rect|line|polyline|polygon|ellipse)>/g, ' />');

let out = `// Generated by scripts/icons.mjs: Phosphor icons (MIT) with only the bold and fill weights. Do not edit.
import { forwardRef, type ReactElement } from 'react';
import { IconBase, type Icon, type IconProps, type IconWeight } from '@phosphor-icons/react';

const icon = (name: string, weights: [string, ReactElement][]) => {
  const w = new Map(weights) as Map<IconWeight, ReactElement>;
  const I = forwardRef<SVGSVGElement, IconProps>((p, ref) => <IconBase ref={ref} {...p} weights={w} />);
  I.displayName = name;
  return I as Icon;
};
`;
for (const n of NAMES) {
  const defs = Object.values(
    await import(`../node_modules/@phosphor-icons/react/dist/defs/${n}.es.js`),
  )[0];
  const parts = WEIGHTS.map(
    w =>
      `['${w}', <>${jsx(renderToStaticMarkup(createElement('g', null, defs.get(w))).replace(/^<g>|<\/g>$/g, ''))}</>]`,
  );
  out += `export const ${n} = icon('${n}', [\n  ${parts.join(',\n  ')},\n]);\n`;
}
writeFileSync('apps/centient/client/src/ui/icons.tsx', out);
console.log(`${NAMES.length} icons written`);
